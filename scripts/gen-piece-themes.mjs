// Generates static/pieces/<board>.css: the chess pieces recolored to match each board theme.
// Reads the embedded SVGs from src/lib/chessground-pieces.css (which uses just two colors, the
// light #FAF0E6 and the dark #282B28) and swaps those for each theme's palette.
// Run: node scripts/gen-piece-themes.mjs   (re-run after changing the palettes or the piece shapes)

import fs from 'node:fs';

const LIGHT = '#FAF0E6', DARK = '#282B28';

// light = white pieces (and their halo), dark = black pieces (and all outlines). Keep in step with src/lib/theme.css.
const PALETTES = {
	brown:  { light: '#F7EBD0', dark: '#3A2514' },
	green:  { light: '#FBFBEF', dark: '#1F2A1B' },
	blue:   { light: '#F4F8FB', dark: '#1D2B3B' },
	purple: { light: '#F6F2FF', dark: '#2A2040' },
	gray:   { light: '#F2F2F2', dark: '#262626' },
	wood:   { light: '#F8E8C8', dark: '#4A2412' }
};

const css = fs.readFileSync( 'src/lib/chessground-pieces.css', 'utf8' );
const rule = /(\.cg-wrap piece\.(\w+)\.(\w+)) \{ background-image: url\('data:image\/svg\+xml;base64,([A-Za-z0-9+/=]+)'\); \}/g;
const pieces = [ ...css.matchAll( rule ) ].map( ( m ) => ( { selector: m[1], svg: Buffer.from( m[4], 'base64' ).toString() } ) );
if ( pieces.length !== 12 ) throw new Error( 'expected 12 pieces, found ' + pieces.length );

for ( const [ board, p ] of Object.entries( PALETTES ) ) {
	let out = `/* Pieces for the "${board}" board theme. Generated by scripts/gen-piece-themes.mjs; do not edit. */\n`;
	for ( const piece of pieces ) {
		const svg = piece.svg.replaceAll( LIGHT, p.light ).replaceAll( DARK, p.dark );
		out += `html[data-board='${board}'] ${piece.selector} { background-image: url('data:image/svg+xml;base64,${Buffer.from( svg ).toString( 'base64' )}'); }\n`;
	}
	fs.writeFileSync( `static/pieces/${board}.css`, out );
	console.log( board, Math.round( out.length / 1024 ) + 'KB' );
}
